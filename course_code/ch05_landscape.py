"""Generates ../figures/ch05/landscape.tikz (the opening cartoon of Chapter 5): the landscape of Chapter 4 and three
colleagues who report on it without surveying it. The Laplace approximation and the Gaussian VI fits in the bottom
strip are computed here for p ~ exp(-C H) on the range [-6.5, 6.5]."""
import numpy as np
import os
from scipy.optimize import minimize
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "figures", "ch05", "landscape.tikz")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
H = lambda x: 3.1 - 2.5 * np.exp(-(x + 2.8) ** 2 / 5.0) - 1.7 * np.exp(-(x - 3.0) ** 2 / 3.5)    # as in Chapter 4
C = 1.5
U = lambda x: C * H(x) + 50.0 * np.maximum(np.abs(x) - 6.5, 0.0) ** 2                    # the range ends at +-6.5
xg = np.linspace(-6.5, 6.5, 2601)
p = np.exp(-U(xg)); p /= np.trapezoid(p, xg)
# Laplace approximation at the deepest point
x_star = minimize(lambda z: U(z[0]), [-2.8]).x[0]
h = 1e-4
curv = (U(x_star + h) - 2 * U(x_star) + U(x_star - h)) / h**2
sd_lap = 1 / np.sqrt(curv)
# Gaussian VI (the ELBO has a single maximum here: started in either valley, it ends in the deep one)
gx, gw = np.polynomial.hermite_e.hermegauss(80); gw = gw / gw.sum()
neg_elbo = lambda q: (gw * U(q[0] + np.exp(q[1]) * gx)).sum() - q[1]
vi = minimize(neg_elbo, [3.0, np.log(0.5)], method="Nelder-Mead", options={"xatol": 1e-10, "fatol": 1e-12})
mu_vi, sd_vi = vi.x[0], np.exp(vi.x[1])
mass_right = np.trapezoid(p * (xg > 0.46), xg)
left = p * (xg <= 0.46); w_left = np.trapezoid(left, xg)
m_left = np.trapezoid(xg * left, xg) / w_left
sd_left = np.sqrt(np.trapezoid((xg - m_left) ** 2 * left, xg) / w_left)
print(f"Laplace at {x_star:.2f} with std {sd_lap:.3f}; Gaussian VI (started at x = 3): mean {mu_vi:.2f}, std {sd_vi:.3f}; "
      f"mass of the right valley {mass_right:.2f}; the deep valley alone: mean {m_left:.2f}, std {sd_left:.3f}")
gauss = lambda x, mu, sd: np.exp(-0.5 * ((x - mu) / sd) ** 2) / (sd * np.sqrt(2 * np.pi))
curve = " ".join(f"({x:.2f},{H(x):.3f})" for x in np.linspace(-6.5, 6.5, 131))
YB, SC = -2.75, 4.0                                          # baseline and vertical scale of the density strip
xs = np.linspace(-6.5, 6.5, 261)
dens = " ".join(f"({x:.2f},{YB + SC * np.interp(x, xg, p):.3f})" for x in xs)
lap = " ".join(f"({x:.2f},{YB + SC * gauss(x, x_star, sd_lap):.3f})" for x in xs if abs(x - x_star) < 3.2)
vig = " ".join(f"({x:.2f},{YB + SC * gauss(x, mu_vi, sd_vi):.3f})" for x in xs if abs(x - mu_vi) < 3.4)
par = " ".join(f"({x:.2f},{H(x_star) + 0.5 * curv / C * (x - x_star) ** 2:.3f})"
               for x in np.linspace(x_star - 1.75, x_star + 1.75, 36))
# the balloon: its lower side rests on the floor of the deep valley, its upper side bulges above it
xl, xr = -4.45, -1.15
floor = [(x, H(x) + 0.04) for x in np.linspace(xl, xr, 25)]
top = [(x, max(H(xl), H(xr)) + 0.04 + 0.62 * np.sqrt(max(1 - ((x - 0.5 * (xl + xr)) / (0.5 * (xr - xl))) ** 2, 0.0)))
       for x in np.linspace(xr, xl, 25)]
balloon = " ".join(f"({x:.3f},{y:.3f})" for x, y in floor + top)
# the search party: walkers on the slope between the valleys, the straight line through their altitudes
party = np.array([-1.55, -1.0, -0.45, 0.1])
slope, icpt = np.polyfit(party, H(party), 1)
lines = []
A = lines.append
A("% Chapter 5: three colleagues report on the landscape of Chapter 4 without surveying it. Generated by code/ch05_landscape.py.")
A(r"\begin{tikzpicture}[line cap=round, line join=round, scale=0.95, every node/.style={font=\footnotesize}]")
A(r"  % a walker with a radio; feet at (#1,#2), size #3")
A(r"  \newcommand{\person}[3]{%")
A(r"    \begin{scope}[shift={(#1,#2)}, scale=#3]")
A(r"      \draw[AccentDark, thick] (0,1.13) circle (0.14);")
A(r"      \draw[AccentDark, thick] (0,0.99) -- (0,0.43);")
A(r"      \draw[AccentDark, thick] (0,0.43) -- (-0.18,0) (0,0.43) -- (0.2,0.03);")
A(r"      \draw[AccentDark, thick] (0,0.9) -- (-0.28,0.64) (0,0.9) -- (0.22,1.12);")
A(r"      \draw[AccentDark, fill=BoxYellow] (0.17,1.12) rectangle (0.29,1.3);")
A(r"    \end{scope}")
A(r"  }")
A(r"  % radio waves above (#1,#2)")
A(r"  \newcommand{\radio}[2]{%")
A(r"    \draw[AccentDark, thin] (#1-0.12,#2) arc (150:30:0.14) (#1-0.2,#2+0.07) arc (150:30:0.23);")
A(r"  }")
A(r"  % the landscape")
A(r"  \fill[BoxGray] (-6.5,0) -- plot[smooth] coordinates {" + curve + r"} -- (6.5,0) -- cycle;")
A(r"  \draw[thick, black!70] plot[smooth] coordinates {" + curve + r"};")
A(r"  \draw[black!70] (-6.5,0) -- (6.5,0);")
A(r"  % (1) variational inference: a balloon inflated in the valley; (2) the Laplace approximation: a bowl")
A(r"  \fill[LiUBlue, opacity=0.3] plot[smooth cycle] coordinates {" + balloon + r"};")
A(r"  \draw[AccentDark] plot[smooth cycle] coordinates {" + balloon + r"};")
A(rf"  \fill[white, opacity=0.7] ({0.5 * (xl + xr) - 0.55:.2f},{max(H(xl), H(xr)) + 0.45:.2f}) ellipse [x radius=0.22, y radius=0.09];")
A(r"  \draw[orange!85!black, thick, densely dashed] plot[smooth] coordinates {" + par + r"};")
A(rf"  \fill[black!70] ({x_star:.2f},{H(x_star):.3f}) circle (0.05);")
A(rf"  \node[align=center, font=\scriptsize, anchor=north, inner sep=2pt, text=orange!70!black] at ({x_star:.2f},{H(x_star) - 0.12:.2f})"
  r" {the bowl (dashed): how the ground\\ curves at the deepest point};")
A(rf"  \node[align=right, font=\scriptsize, anchor=south east, inner sep=2pt, text=AccentDark] at ({xr - 0.45:.2f},{max(H(xl), H(xr)) + 0.72:.2f})"
  r" {the balloon: inflated in the valley,\\ it fills the valley from within\\ and never crosses a wall};")
A(r"  % (2) the ensemble: a search party without slope meters")
A(rf"  \draw[AccentDark, densely dotted] ({party[0] - 0.6:.2f},{slope * (party[0] - 0.6) + icpt:.3f}) -- ({party[-1] + 0.6:.2f},{slope * (party[-1] + 0.6) + icpt:.3f});")
for xp in party:
    A(rf"  \person{{{xp:.3f}}}{{{H(xp):.3f}}}{{0.6}} \radio{{{xp + 0.14:.3f}}}{{{H(xp) + 0.86:.3f}}}")
    A(rf"  \draw[-{{Latex[length=1.6mm]}}, AccentDark] ({xp - 0.12:.3f},{H(xp) - 0.12:.3f}) -- ({xp - 0.55:.3f},{H(xp) - 0.12 - 0.43 * slope:.3f});")
A(rf"  \node[draw=AccentDark, fill=white, rounded corners=8pt, align=left, font=\scriptsize, anchor=south, inner sep=4pt] at (-0.25,{H(0.1) + 1.25:.2f})"
  r" {No slope meters: we radio our\\ altitudes, fit a straight line,\\ and move as a team.};")
A(r"  % the second valley, which neither the bowl nor the balloon sees")
A(rf"  \node[align=center, font=\scriptsize, text=black!70, anchor=north] at (3.0,{H(3.0) - 0.12:.2f}) {{a second valley,\\ seen by neither}};")
A(r"  % the reports, against the posterior")
A(rf"  \draw[black!70] (-6.5,{YB}) -- (6.5,{YB});")
A(r"  \fill[LiUBlue, opacity=0.3] plot[smooth] coordinates {" + f"(-6.50,{YB}) " + dens + f" (6.50,{YB})" + r"} -- cycle;")
A(r"  \draw[LiUBlue!70!black] plot[smooth] coordinates {" + dens + r"};")
A(r"  \draw[orange!85!black, thick, densely dashed] plot[smooth] coordinates {" + lap + r"};")
A(r"  \draw[AccentDark, thick] plot[smooth] coordinates {" + vig + r"};")
A(rf"  \node[anchor=west, font=\scriptsize, text=orange!70!black] at ({x_star + 0.95:.2f},{YB + SC * gauss(x_star, x_star, sd_lap) - 0.25:.2f}) {{bowl (Laplace)}};")
A(rf"  \node[anchor=west, font=\scriptsize, text=AccentDark] at ({mu_vi + 0.75:.2f},{YB + SC * gauss(mu_vi, mu_vi, sd_vi) - 0.1:.2f}) {{balloon (VI)}};")
A(rf"  \node[anchor=west, font=\scriptsize, align=left] at (-6.5,{YB + 1.25:.2f}) {{posterior\\ $\propto e^{{-U(\vecx)}}$}};")
A(rf"  \node[anchor=east, font=\scriptsize, align=right] at (6.5,{H(6.5) + 0.45:.2f}) {{landscape $U(\vecx) = -\log p(\vecx \mid \vecy)$}};")
A(r"\end{tikzpicture}")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, "; straight line through the party: slope", round(slope, 3))
