"""Generates ../figures/ch04/landscape.tikz (the opening cartoon of Chapter 4) with hard-coded coordinates."""
import numpy as np
import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "figures", "ch04", "landscape.tikz")
H = lambda x: 3.1 - 2.5 * np.exp(-(x + 2.8) ** 2 / 5.0) - 1.7 * np.exp(-(x - 3.0) ** 2 / 3.5)
C = 1.5                                         # p ~ exp(-C h): about 75 % of the mass in the deep valley
xg = np.linspace(-6.5, 6.5, 2601)
p = np.exp(-C * H(xg)); p /= np.trapezoid(p, xg)
cdf = np.cumsum(p) * (xg[1] - xg[0]); cdf /= cdf[-1]
K = 26
xs = np.interp((np.arange(K) + 0.5) / K, cdf, xg)          # the ideal survey: quantiles of the posterior
curve = " ".join(f"({x:.2f},{H(x):.3f})" for x in np.linspace(-6.5, 6.5, 131))
# histogram of the flags
edges = np.linspace(-6.5, 6.5, 21); bw = edges[1] - edges[0]
cnt, _ = np.histogram(xs, edges)
YB, SC = -2.75, 0.30                                         # baseline of the histogram, height per flag
dens = " ".join(f"({x:.2f},{YB + SC * K * bw * np.interp(x, xg, p):.3f})" for x in np.linspace(-6.5, 6.5, 131))
xh = -0.75; yh = H(xh)
lines = []
A = lines.append
A("% The survey of Chapter 4: in fog, a hiker who can only measure the altitude where she stands plants a flag at")
A("% every step, and the flags end up dense where the landscape U = -log p is low. Generated by code/ch04_landscape.py.")
A(r"\begin{tikzpicture}[line cap=round, line join=round, scale=0.95, every node/.style={font=\footnotesize}]")
A(r"  % hiker with a lantern (left hand) and a flag ready to be planted (right hand); feet at (#1,#2)")
A(r"  \newcommand{\hiker}[2]{%")
A(r"    \fill[BoxYellow-dark, opacity=0.55] (#1-0.42,#2+0.55) circle (0.55);")
A(r"    \draw[AccentDark, thick] (#1,#2+1.13) circle (0.14);")
A(r"    \draw[AccentDark, thick] (#1,#2+0.99) -- (#1,#2+0.43);")
A(r"    \draw[AccentDark, thick] (#1,#2+0.43) -- (#1-0.18,#2) (#1,#2+0.43) -- (#1+0.2,#2+0.03);")
A(r"    \draw[AccentDark, thick] (#1,#2+0.9) -- (#1-0.3,#2+0.62) (#1,#2+0.9) -- (#1+0.25,#2+1.12);")
A(r"    \draw[AccentDark] (#1-0.3,#2+0.62) -- (#1-0.3,#2+0.52);")
A(r"    \draw[AccentDark, fill=BoxYellow] (#1-0.36,#2+0.36) rectangle (#1-0.24,#2+0.52);")
A(r"    \draw[AccentDark, thick] (#1+0.25,#2+0.8) -- (#1+0.25,#2+1.45);")
A(r"    \fill[LiUBlue] (#1+0.25,#2+1.45) -- (#1+0.47,#2+1.37) -- (#1+0.25,#2+1.29) -- cycle;")
A(r"  }")
A(r"  % the landscape")
A(r"  \fill[BoxGray] (-6.5,0) -- plot[smooth] coordinates {" + curve + r"} -- (6.5,0) -- cycle;")
A(r"  \draw[thick, black!70] plot[smooth] coordinates {" + curve + r"};")
A(r"  \draw[black!70] (-6.5,0) -- (6.5,0);")
A(r"  % the flags (samples)")
for x in xs:
    y = H(x)
    A(rf"  \draw[AccentDark] ({x:.3f},{y:.3f}) -- ({x:.3f},{y + 0.34:.3f}); \fill[LiUBlue] ({x:.3f},{y + 0.34:.3f}) -- ({x + 0.15:.3f},{y + 0.285:.3f}) -- ({x:.3f},{y + 0.23:.3f}) -- cycle;")
A(r"  % the deepest point, which the hiker of Chapter 2 was looking for")
A(rf"  \node[star, star points=5, star point ratio=2.2, fill=white, draw=black!70, inner sep=1.1pt] at (-2.8,{H(-2.8) - 0.28:.3f}) {{}};")
A(rf"  \node[font=\scriptsize, text=black!70, align=right, anchor=east] at (-3.05,{H(-2.8) - 0.3:.3f}) {{the deepest point,\\ sought in \Cref{{ch:regularization}}}};")
A(r"  % fog")
for (fx, fy, a, b) in [(-5.3, 2.75, 1.5, 0.28), (-1.6, 2.35, 1.3, 0.22), (1.6, 2.95, 1.6, 0.3), (4.9, 2.55, 1.5, 0.25),
                       (-3.6, 1.45, 1.0, 0.18), (3.6, 1.95, 1.0, 0.18), (2.9, 1.25, 1.3, 0.22), (5.6, 3.3, 0.9, 0.2),
                       (-4.9, 3.35, 1.0, 0.2), (0.4, 1.75, 0.8, 0.16)]:
    A(rf"  \fill[white, opacity=0.6] ({fx},{fy}) ellipse [x radius={a}, y radius={b}];")
A(r"  % the hiker and her thoughts")
A(rf"  \hiker{{{xh:.3f}}}{{{yh:.3f}}}")
A(rf"  \draw[AccentDark, fill=white] ({xh + 0.35:.2f},{yh + 1.62:.2f}) circle (0.05) ({xh + 0.55:.2f},{yh + 1.86:.2f}) circle (0.08);")
A(rf"  \node[draw=AccentDark, fill=white, rounded corners=8pt, align=left, font=\scriptsize, anchor=south west, inner sep=4pt] at ({xh + 0.45:.2f},{yh + 1.95:.2f})"
  r" {I only feel the altitude where I stand.\\ Step or stay, plant a flag, repeat.};")
A(r"  % the record: flags per stretch of the range, and the posterior")
A(rf"  \draw[black!70] (-6.5,{YB}) -- (6.5,{YB});")
for k in range(len(cnt)):
    if cnt[k] > 0:
        A(rf"  \fill[LiUBlue, opacity=0.7] ({edges[k] + 0.03:.3f},{YB}) rectangle ({edges[k + 1] - 0.03:.3f},{YB + SC * cnt[k]:.3f});")
A(r"  \draw[AccentDark, thick] plot[smooth] coordinates {" + dens + r"};")
A(rf"  \node[anchor=west, font=\scriptsize, align=left] at (-6.5,{YB + 1.25:.2f}) {{flags per stretch\\ of the range}};")
A(rf"  \node[anchor=east, font=\scriptsize, align=right, text=AccentDark] at (6.5,{YB + 1.0:.2f}) {{$\propto e^{{-U(\vecx)}} \propto p(\vecx \mid \vecy)$}};")
A(rf"  \node[anchor=east, font=\scriptsize, align=right] at (6.5,{H(6.5) + 0.45:.2f}) {{landscape $U(\vecx) = -\log p(\vecx \mid \vecy)$}};")
A(r"\end{tikzpicture}")
open(OUT, "w").write("\n".join(lines) + "\n")
print("flags per bin", cnt.tolist(), "max", cnt.max(), "hiker at", round(xh, 2), round(yh, 2))
